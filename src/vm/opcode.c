OpcodeFlag get_opcode_flags(Opcode opcode)
{
    if ((unsigned)opcode >= OpCount) {
        return OpFlagNone;
    }
    
    return opcode_flags[opcode];
}

OpcodeRegisterFlag get_opcode_register_flag(Opcode opcode)
{
    if ((unsigned)opcode >= OpCount) {
        return OpRegisterNone;
    }

    return OpcodeRegisterFlags[opcode];
}
